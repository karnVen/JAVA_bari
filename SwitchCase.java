class SwitchCase{
    public static void main(String[] args) {
        int n=3;
        if(n==1){
            System.out.println("one");
        }else if(n==2){
            System.out.println("two");
        }else if(n==3){
            System.out.println("third");
        }else{
            System.out.println("invalid");
        }
    }

}